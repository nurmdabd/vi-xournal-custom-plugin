-- Generates keybindings.md from keybindings.lua.
-- Run it from the plugin folder: lua documentation.lua
require "keybindings"
require "modes"

-- accelerator names as they should be shown to people
local KEY_NAMES = {
  space   = "Space",
  greater = ">",
  less    = "<",
  plus    = "+",
  minus   = "-",
  grave   = "`"
}

local MODIFIER_NAMES = {Shift = "Shift", Ctrl = "Ctrl", Control = "Ctrl", Primary = "Ctrl", Alt = "Alt"}

-- splits "<Ctrl><Shift>a" into "Ctrl+Shift+" and "a"
local function splitKey(key)
  local mods = ""
  for mod in key:gmatch("<%a+>") do mods = mods .. mod end
  local base = key:sub(#mods + 1)
  return mods:gsub("<(%a+)>", function(m) return (MODIFIER_NAMES[m] or m) .. "+" end), base
end

local function formatKey(key)
  local mods, base = splitKey(key)
  local text = mods .. (KEY_NAMES[base] or base)
  -- a key containing a backtick needs double backticks as code span delimiters
  if text:find("`") then return "`` " .. text .. " ``" end
  return "`" .. text .. "`"
end

-- "<Shift>plus" next to "plus" only exists because "+" needs Shift on many
-- keyboard layouts, so it is left out of the docs
local function isShiftedSymbol(key)
  local base = key:match("^<Shift>(.*)$")
  return base ~= nil and base ~= "space" and KEY_NAMES[base] ~= nil, base
end

local function formatKeys(keys)
  local present, formatted = {}, {}
  for _, key in ipairs(keys) do present[key] = true end
  for _, key in ipairs(keys) do
    local shifted, base = isShiftedSymbol(key)
    if not (shifted and present[base]) then table.insert(formatted, formatKey(key)) end
  end
  return table.concat(formatted, ", ")
end

-- sort by the key itself, unshifted before shifted (a, <Shift>a, b, ...)
-- letters first, then named keys (Space, >, +, ...)
local function sortName(key)
  local _, base = splitKey(key)
  return KEY_NAMES[base] and ("~" .. base) or base
end

local function keyOrder(a, b)
  local baseA, baseB = sortName(a), sortName(b)
  if baseA ~= baseB then return baseA < baseB end
  return #a < #b
end

local function sortedKeys(tbl, order)
  local keys = {}
  for key in pairs(tbl) do table.insert(keys, key) end
  table.sort(keys, order)
  return keys
end

local function capitalize(s)
  return s:sub(1, 1):upper() .. s:sub(2)
end

-- "moreTool" -> "More tool"
local function modeName(mode)
  return capitalize(mode:gsub("(%u)", function(c) return " " .. c:lower() end))
end

local function anchor(mode)
  return mode:lower() .. "-mode"
end

-- actions per mode (mode switches are listed separately), and the keys that enter each mode
local actions = {}
local entry = {}
for _, mode in ipairs(ALL_MODES) do
  actions[mode] = {}
  entry[mode] = {normal = {}, sticky = {}}
end

for _, binding in pairs(keybindings) do
  if binding.enters then
    assert(entry[binding.enters], "mode '" .. binding.enters .. "' is missing from ALL_MODES")
    local kind = binding.sticky and "sticky" or "normal"
    for _, key in ipairs(binding.buttons) do table.insert(entry[binding.enters][kind], key) end
  else
    for _, mode in pairs(binding.modes) do
      assert(actions[mode], "mode '" .. mode .. "' is missing from ALL_MODES")
      actions[mode][binding.description] = binding.buttons
    end
  end
end

local function entryKeys(mode)
  table.sort(entry[mode].normal, keyOrder)
  table.sort(entry[mode].sticky, keyOrder)
  return formatKeys(entry[mode].normal), formatKeys(entry[mode].sticky)
end

local output_file = assert(io.open("keybindings.md", "w"))
io.output(output_file)

io.write([[
# Key bindings

<!-- Generated by documentation.lua from keybindings.lua. Do not edit by hand:
     change keybindings.lua, then run `lua documentation.lua` in the plugin folder. -->

vi-xournalpp starts in **tool mode**. Press a mode key to enter another mode:
the next key runs one action there and takes you back to tool mode.
Enter a mode with **Shift** to make it **sticky**: it stays active until you press `t`.
A key that does nothing in a one-shot mode acts as it would in tool mode,
a one-shot mode ends by itself after ]] .. MODE_TIMEOUT .. [[ seconds without a key press,
and `t` returns to tool mode from every mode.

]])

-- overview of the modes
io.write("| Mode | Enter | Sticky |\n|---|---|---|\n")
for _, mode in ipairs(ALL_MODES) do
  local normal, sticky = entryKeys(mode)
  io.write("| [" .. modeName(mode) .. "](#" .. anchor(mode) .. ") | " .. normal .. " | " .. sticky .. " |\n")
end
io.write("\n")

-- one section per mode, entries sorted alphabetically, so the output is stable
for _, mode in ipairs(ALL_MODES) do
  local normal, sticky = entryKeys(mode)
  local heading = modeName(mode) .. " mode (" .. normal
  if sticky ~= "" then heading = heading .. ", sticky " .. sticky end
  -- the explicit anchor keeps the overview links working despite the keys in the heading
  io.write('<a id="' .. anchor(mode) .. '"></a>\n\n')
  io.write("## " .. heading .. ")\n\n")
  for _, descr in ipairs(sortedKeys(actions[mode])) do
    local keys = actions[mode][descr]
    table.sort(keys, keyOrder)
    io.write("* " .. descr .. ": " .. formatKeys(keys) .. "\n")
  end
  io.write("\n")
end

-- overview table: one row per key, one column per mode
local byKey = {}
for _, binding in pairs(keybindings) do
  for _, key in ipairs(binding.buttons) do
    byKey[key] = byKey[key] or {}
    for _, mode in pairs(binding.modes) do
      byKey[key][mode] = binding.description
    end
  end
end

local columns = {}
for _, mode in ipairs(ALL_MODES) do table.insert(columns, modeName(mode)) end

io.write("## All keys by mode\n\n")
io.write("| Key | " .. table.concat(columns, " | ") .. " |\n")
io.write("|---" .. string.rep("|---", #ALL_MODES) .. "|\n")
local function sameMeaning(a, b)
  for _, mode in ipairs(ALL_MODES) do
    if a[mode] ~= b[mode] then return false end
  end
  return true
end

for _, key in ipairs(sortedKeys(byKey, keyOrder)) do
  local shifted, base = isShiftedSymbol(key)
  if shifted and byKey[base] and sameMeaning(byKey[key], byKey[base]) then goto continue end
  local cells = {}
  for _, mode in ipairs(ALL_MODES) do
    table.insert(cells, byKey[key][mode] or "")
  end
  io.write("| " .. formatKey(key) .. " | " .. table.concat(cells, " | ") .. " |\n")
  ::continue::
end

io.close(output_file)
